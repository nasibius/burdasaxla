const DICTS: Record<Lang, Dict> = { az, en };

export function makeT(lang: Lang) {
  return (key: string) => DICTS[lang][key] ?? DICTS.az[key] ?? key;
}

export function ruleTitle(rule: string, lang: Lang) {
  return RULE_TEXT[rule]?.[lang][0] ?? rule;
}
export function ruleText(rule: string, lang: Lang) {
  return RULE_TEXT[rule]?.[lang][1] ?? "";
}

export function fmtDist(m: number | undefined, lang: Lang) {
  if (m == null) return "—";
  const t = makeT(lang);
  return m >= 1000 ? `${(m / 1000).toFixed(1)} ${t("km")}` : `${Math.round(m)} ${t("m")}`;
}
