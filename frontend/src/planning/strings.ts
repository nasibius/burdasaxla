export function makePT(lang: Lang) {
  const d = lang === "en" ? en : az;
  return (k: string) => d[k] ?? az[k] ?? k;
}

import type { PlanningItem } from "../types";

/** Localised "why" sentence built from the same fields the engine used (the API keeps an English one). */
export function whyText(i: PlanningItem, lang: Lang) {
  const p = makePT(lang);
  const f = (k: string, v: Record<string, string | number>) => Object.entries(v).reduce((s, [a, b]) => s.replace(`{${a}}`, String(b)), p(k));
  if (i.type === "candidate") {
    return f("why_cand", { d: i.walk_distance_to_gap_m, c: i.current_avg_walk_to_verified_m }) + ".";
  }
  const st = i.coverage_states;
  const parts = [f("why_task", { n: i.access_nodes })];
  if (i.transit_hubs.length) parts.push(p("why_transit"));
  if (st.INVENTORY_UNKNOWN) parts.push(f("why_unknown", { n: st.INVENTORY_UNKNOWN }));
  if (st.POTENTIAL_COVERAGE_GAP) parts.push(f("why_gap", { n: st.POTENTIAL_COVERAGE_GAP }));
  if (st.NETWORK_UNRELIABLE) parts.push(f("why_net", { n: st.NETWORK_UNRELIABLE }));
  return parts.join("; ") + ".";
}
